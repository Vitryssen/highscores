// Regenerates supabase/functions/_shared/shortcodes.ts from emojibase-data.
// Run: node scripts/generate-shortcodes.mjs   (after updating emojibase-data)
// Priority when names clash: Slack (iamcal) > GitHub > JoyPixels (Discord-style names such as
// :first_place:). Skin-tone variants are skipped.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const data = require('emojibase-data/en/data.json');
const emojiByHex = new Map(data.flatMap((e) => [[e.hexcode, e.emoji], ...(e.skins ?? []).map((s) => [s.hexcode, s.emoji])]));

const map = new Map();
for (const set of ['iamcal', 'github', 'joypixels']) {
  const codes = require(`emojibase-data/en/shortcodes/${set}.json`);
  for (const [hex, names] of Object.entries(codes)) {
    const emoji = emojiByHex.get(hex);
    if (!emoji) continue;
    for (const name of [].concat(names)) {
      // Skin-tone variants never appear in -dle results and would triple the file size.
      if (/_tone\d|skin[_-]tone/.test(name)) continue;
      if (!map.has(name)) map.set(name, emoji);
    }
  }
}

const entries = [...map].sort(([a], [b]) => a.localeCompare(b));
const body = entries.map(([name, emoji]) => `${name}\t${emoji}`).join('\n');
const out = `// GENERATED by web/scripts/generate-shortcodes.mjs from emojibase-data: do not edit by hand.
// Slack/GitHub/Discord shortcodes (${entries.length}) that show up in copied -dle results. Values are
// plain emoji strings, never HTML. Unknown shortcodes are left as-is.

const RAW = ${JSON.stringify(body)};

export const SHORTCODES: Record<string, string> = Object.fromEntries(
  RAW.split('\\n').map((line) => line.split('\\t')),
);
`;
const target = new URL('../../supabase/functions/_shared/shortcodes.ts', import.meta.url);
writeFileSync(target, out);
console.log(`wrote ${entries.length} shortcodes (${Math.round(readFileSync(target).length / 1024)} kB)`);
